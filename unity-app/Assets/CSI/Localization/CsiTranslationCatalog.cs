    // Source-language phrases and numeric-message fragments. Identifiers remain verbatim.
    internal static class CsiTranslationCatalog
    {
        private static readonly Dictionary<string, string> Exact = new Dictionary<string, string>(StringComparer.Ordinal);
        private static readonly List<KeyValuePair<Regex, string>> Phrases = new List<KeyValuePair<Regex, string>>();
        private static readonly Regex DemoUpcomingTurn = new Regex(@"\bIn (?<distance>[0-9]+(?:[.,][0-9]+)?) m, turn (?<turn>left|right|back)\b", RegexOptions.CultureInvariant | RegexOptions.IgnoreCase);
        private static readonly Regex DemoImmediateTurn = new Regex(@"\bTurn (?<turn>left|right|back) now\b", RegexOptions.CultureInvariant | RegexOptions.IgnoreCase);
        private static readonly Regex DemoContinue = new Regex(@"\bContinue (?<distance>[0-9]+(?:[.,][0-9]+)?) m to (?<target>grid target|demo entrance)\b", RegexOptions.CultureInvariant | RegexOptions.IgnoreCase);
        private static readonly Regex Protected = new Regex(@"https?://[^\s]+|\b(?:KNN|GCN|ConcatMLP-mask|ConcatMLP|F-MLP|MLP-mask|MLP|MOCK|piA_apX|piA_apY|piB_apX|piB_apY)\b", RegexOptions.CultureInvariant);
        static CsiTranslationCatalog()
        {
            foreach (string row in Data.Split('\n'))
            {
                string entry = row.TrimEnd('\r'); int at = entry.IndexOf("=>", StringComparison.Ordinal);
                if (at < 0) continue;
                string en = entry.Substring(0, at).Replace("\\n", "\n");
                string zh = entry.Substring(at + 2).Replace("\\n", "\n");
                Exact[en] = zh;
            }
            var ordered = new List<string>(Exact.Keys); ordered.Sort((a, b) => b.Length.CompareTo(a.Length));
            foreach (string key in ordered)
            {
                string pattern = Regex.Escape(key);
                if (char.IsLetterOrDigit(key[0])) pattern = @"(?<![A-Za-z0-9_])" + pattern;
                if (char.IsLetterOrDigit(key[key.Length - 1])) pattern += @"(?![A-Za-z0-9_])";
                Phrases.Add(new KeyValuePair<Regex, string>(new Regex(pattern, RegexOptions.CultureInvariant), Exact[key]));
            }
        }
        public static string Chinese(string english)
        {
            string exact; if (Exact.TryGetValue(english, out exact)) return exact;
            // DemoNavigationRoute composes these messages, including lowercase turn actions.
            // Match the whole instruction grammar (also inside the AR lab status line),
            // rather than leaving a mixture of English fragments and translated words.
            english = DemoUpcomingTurn.Replace(english, m => "前方 " + m.Groups["distance"].Value + " m 后" + DemoTurn(m.Groups["turn"].Value));
            english = DemoImmediateTurn.Replace(english, m => "立即" + DemoTurn(m.Groups["turn"].Value));
            english = DemoContinue.Replace(english, m => "继续前进 " + m.Groups["distance"].Value + " m 至"
                + (m.Groups["target"].Value.Equals("grid target", StringComparison.OrdinalIgnoreCase) ? "格点终点" : "演示入口"));
            // Protect raw model names, URLs and source identifiers before composing dynamic UI.
            var tokens = new List<string>();
            string value = Protected.Replace(english, m => { tokens.Add(m.Value); return "\uE000" + (tokens.Count - 1) + "\uE001"; });
            foreach (var phrase in Phrases) value = phrase.Key.Replace(value, m => phrase.Value);
            for (int i = 0; i < tokens.Count; i++) value = value.Replace("\uE000" + i + "\uE001", tokens[i]);
            return value;
        }
        private static string DemoTurn(string direction)
        { return direction.Equals("left", StringComparison.OrdinalIgnoreCase) ? "左转" : direction.Equals("right", StringComparison.OrdinalIgnoreCase) ? "右转" : "掉头"; }
