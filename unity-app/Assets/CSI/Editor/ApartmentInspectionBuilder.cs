using System;
using System.Collections.Generic;
using System.IO;
using System.Security.Cryptography;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace CsiApp.Editor
{
    /// <summary>Generate a standalone, editable inspection scene from confirmed survey data.</summary>
    public static class ApartmentInspectionBuilder
    {
        public const string ScenePath = "Assets/CSI/Scenes/ApartmentInspection.unity";
        private const string GeneratedRoot = "Assets/CSI/Generated/ApartmentInspection";

        [MenuItem("CSI/Generate field inspection model")]
        public static void BuildAll()
        {
            // Work in an additive scene: never discard an unrelated scene's unsaved edits.
            var existing = SceneManager.GetSceneByPath(ScenePath);
            if (existing.IsValid() && existing.isLoaded && existing.isDirty)
                throw new InvalidOperationException("Save the open ApartmentInspection scene before regenerating it.");
            if (existing.IsValid() && existing.isLoaded) EditorSceneManager.CloseScene(existing, true);
            var data = ApartmentMap.Current;
            var evidence = ValidateGeometry(data);
            string run = "run_" + DateTime.UtcNow.ToString("yyyyMMdd_HHmmss_fff");
            string assets = GeneratedRoot + "/" + run;
            Directory.CreateDirectory(assets); Directory.CreateDirectory("Assets/CSI/Scenes"); AssetDatabase.Refresh();
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
            SceneManager.SetActiveScene(scene);
            var owner = new GameObject("Apartment inspection / metre scale / cutaway heights NOT surveyed");
            var model = owner.AddComponent<ApartmentWorldModel>();
            model.Initialize(true);
            if (model.FloorCount != 5) throw new InvalidOperationException("Expected five known floor regions, without unknown space.");
            var cameraObject = new GameObject("Inspection camera / virtual overview", typeof(Camera));
            var camera = cameraObject.GetComponent<Camera>();
            camera.clearFlags = CameraClearFlags.SolidColor; camera.backgroundColor = new Color32(239, 243, 238, 255);
            camera.orthographic = true; camera.aspect = 1.6f; camera.nearClipPlane = .05f; camera.farClipPlane = 60;
            Rect bounds = data.PlanBounds;
            Vector3 center = ApartmentMap.ToWorld(bounds.center.x, bounds.center.y);
            Quaternion rotation = Quaternion.Euler(64, -12, 0);
            camera.transform.rotation = rotation; camera.transform.position = center + rotation * Vector3.back * 16;
            float halfWidth = 0, halfHeight = 0;
            foreach (float x in new[] { bounds.xMin, bounds.xMax })
                foreach (float y in new[] { bounds.yMin, bounds.yMax })
                    foreach (float h in new[] { 0f, model.wallDisplayHeight })
                    {
                        Vector3 offset = Quaternion.Inverse(rotation) * (ApartmentMap.ToWorld(x, y, h) - center);
                        halfWidth = Mathf.Max(halfWidth, Mathf.Abs(offset.x)); halfHeight = Mathf.Max(halfHeight, Mathf.Abs(offset.y));
                    }
            camera.orthographicSize = Mathf.Max(halfHeight + .5f, (halfWidth + .5f) / camera.aspect);
            model.SetLabelsFacing(camera);

            int meshCount = 0, materialCount = 0;
            foreach (var filter in owner.GetComponentsInChildren<MeshFilter>(true))
            {
                if (filter.GetComponent<TextMesh>() != null) continue; // Dynamic font geometry is regenerated by TextMesh.
                if (filter.sharedMesh == null || AssetDatabase.Contains(filter.sharedMesh)) continue;
                filter.sharedMesh.name = "Inspection mesh " + meshCount;
                AssetDatabase.CreateAsset(filter.sharedMesh, assets + "/mesh_" + meshCount.ToString("D3") + ".asset"); meshCount++;
            }
            foreach (var material in model.GetGeneratedMaterialsForPersistence())
            {
                if (material == null || AssetDatabase.Contains(material)) continue;
                AssetDatabase.CreateAsset(material, assets + "/material_" + materialCount.ToString("D2") + ".mat"); materialCount++;
            }
            model.SealAsInspectionAssets();
            evidence.floor_count = model.FloorCount; evidence.mesh_asset_count = meshCount; evidence.material_asset_count = materialCount;
            evidence.scene_path = ScenePath; evidence.generated_asset_folder = assets;
            evidence.generated_utc = DateTime.UtcNow.ToString("o");
            string reportPath = assets + "/inspection-evidence.json";
            File.WriteAllText(reportPath, JsonUtility.ToJson(evidence, true) + Environment.NewLine);
            AssetDatabase.Refresh(); AssetDatabase.SaveAssets();
            if (!EditorSceneManager.SaveScene(scene, ScenePath)) throw new InvalidOperationException("Could not save inspection scene.");
            Selection.activeGameObject = owner;
            Debug.Log("CSI_INSPECTION_MODEL_PASS: " + ScenePath + " | " + reportPath + " | 1 unit = 1 metre, visual cutaway heights only.");
        }

        public static InspectionEvidence ValidateGeometry(SiteMapData data)
        {
            string resourcePath = Path.Combine(Application.dataPath, "Resources/Maps/apartment_v1_2026-10-10.json");
            string sourcePath = Path.GetFullPath(Path.Combine(Application.dataPath, "../../maps/apartment_v1_2026-10-10.json"));
            if (!File.Exists(sourcePath) || !File.Exists(resourcePath)) throw new InvalidOperationException("Both canonical map and Resources copy are required.");
            string sourceHash = Hash(sourcePath), resourceHash = Hash(resourcePath);
            if (sourceHash != resourceHash) throw new InvalidOperationException("Map source and runtime resource SHA-256 differ.");
            var freshlyRead = JsonUtility.FromJson<SiteMapData>(File.ReadAllText(resourcePath));
            if (JsonUtility.ToJson(data) != JsonUtility.ToJson(freshlyRead))
                throw new InvalidOperationException("ApartmentMap cache is older than the source. Reload the Unity domain or restart the Editor before generation.");
            if (data.grid.points.Length != 15 || data.grid.edges.Length != 22 || data.openings.Length != 3)
                throw new InvalidOperationException("Unexpected point/edge/opening counts.");
            var labels = new HashSet<int>(); var edges = new HashSet<string>();
            foreach (var point in data.grid.points)
            {
                if (!labels.Add(point.label) || point.label != point.j * data.grid.columns + point.i ||
                    !Near(point.x_m, point.i * data.grid.spacing_m) || !Near(point.y_m, point.j * data.grid.spacing_m))
                    throw new InvalidOperationException("Inconsistent grid coordinates or labels.");
            }
            foreach (var edge in data.grid.edges)
            {
                var a = data.FindPoint(edge.from); var b = data.FindPoint(edge.to);
                string key = Math.Min(edge.from, edge.to) + ":" + Math.Max(edge.from, edge.to);
                if (a == null || b == null || !edges.Add(key) || Math.Abs(a.i - b.i) + Math.Abs(a.j - b.j) != 1 ||
                    !Near(Vector2.Distance(new Vector2(a.x_m, a.y_m), new Vector2(b.x_m, b.y_m)), edge.length_m))
                    throw new InvalidOperationException("Non-neighbor or duplicate edge.");
            }
            foreach (var opening in data.openings)
            {
                var a = new Vector2(opening.start_xy_m[0], opening.start_xy_m[1]); var b = new Vector2(opening.end_xy_m[0], opening.end_xy_m[1]);
                if (!Near(Vector2.Distance(a, b), opening.span_m) || !Near(opening.span_m, .8f)) throw new InvalidOperationException("Opening width mismatch.");
                foreach (var boundary in data.boundaries)
                {
                    if (boundary.kind == "open_connection" || boundary.kind == "region_boundary_unspecified") continue;
                    bool vertical = Near(a.x, b.x); int fixedAxis = vertical ? 0 : 1, along = 1 - fixedAxis;
                    if (Near(boundary.start_xy_m[fixedAxis], opening.start_xy_m[fixedAxis]) && Near(boundary.end_xy_m[fixedAxis], opening.start_xy_m[fixedAxis]))
                    {
                        float lo = Mathf.Max(Mathf.Min(opening.start_xy_m[along], opening.end_xy_m[along]), Mathf.Min(boundary.start_xy_m[along], boundary.end_xy_m[along]));
                        float hi = Mathf.Min(Mathf.Max(opening.start_xy_m[along], opening.end_xy_m[along]), Mathf.Max(boundary.start_xy_m[along], boundary.end_xy_m[along]));
                        if (hi - lo > .0001f) throw new InvalidOperationException("A solid boundary obstructs " + opening.id);
                    }
                }
            }
            var unknown = data.FindRegion("unknown");
            if (unknown == null || unknown.model_role != "excluded_unknown") throw new InvalidOperationException("Unknown space must remain excluded.");
            return new InspectionEvidence {
                map_id = data.metadata.map_id, source_sha256 = sourceHash, resource_sha256 = resourceHash,
                point_count = labels.Count, undirected_edge_count = edges.Count, opening_count = data.openings.Length,
                geometry_validation = "PASS: matching source/resource hashes, labels/spacing, unique four-neighbor edges, opening spans and no blocked openings, unknown excluded",
                interpretation = "Net-space planar abstraction; 1 local Unity unit = 1 metre. Heights are temporary display values. No AR alignment, T01, exit selection, or physical accuracy is validated here."
            };
        }
        private static bool Near(float a, float b) { return Mathf.Abs(a - b) < .0001f; }
        private static string Hash(string path)
        { using (var sha = SHA256.Create()) using (var stream = File.OpenRead(path)) return BitConverter.ToString(sha.ComputeHash(stream)).Replace("-", ""); }
        [Serializable] public sealed class InspectionEvidence
        {
            public string generated_utc, map_id, source_sha256, resource_sha256, scene_path, generated_asset_folder, geometry_validation, interpretation;
            public int point_count, undirected_edge_count, opening_count, floor_count, mesh_asset_count, material_asset_count;
        }
    }
}
